def gost_table(body_type: str = "ball") -> list[float]:
    """Отсортированный список стандартных диаметров для типа тела качения."""
    if body_type == "ball":
        return GOST_BALL_DIAMETERS
    return sorted(GOST_ROLLER_DIAMETERS)   # ключи словаря = диаметры


def round_up_to_gost(dtk: float, body_type: str = "ball") -> float:
    """
    Округлить диаметр ТЕЛА КАЧЕНИЯ вверх до ближайшего стандартного по ГОСТ.
    dtk: расчётный диаметр тела качения, мм.
    body_type: "ball" — ГОСТ 3722-81, "roller" — ГОСТ 22696-77.
    """
    diameters = gost_table(body_type)
    idx = bisect.bisect_left(diameters, dtk)
    if idx >= len(diameters):
        raise ValueError(
            f"dтк={dtk:.3f} мм больше максимального стандартного "
            f"({diameters[-1]} мм) по ГОСТ"
        )
    return diameters[idx]